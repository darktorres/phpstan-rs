//! The lazy context load, end to end: a context file that a name reaches is
//! read, and an include in it reads the file it names, so a function that only
//! that file declares is known, as it is when every context file is read.

mod common;

use common::{TempDir, bin};

const LOADER: &str = "<?php\nnamespace Acme;\n\nclass Loader\n{\n    public function run(): int\n    {\n        return helper_value();\n    }\n}\n";

const HELPERS: &str =
    "<?php\nnamespace Acme;\n\nfunction helper_value(): int\n{\n    return 1;\n}\n";

const MAIN: &str = "<?php\nnamespace App;\n\nuse Acme\\Loader;\n\nfunction f(): int\n{\n    return (new Loader())->run();\n}\n";

/// A project with a Composer vendor whose `Loader` class is a classmap entry and
/// whose `acme` directory is a PSR-4 prefix, so that both are lazy context
/// files. The `Loader` file includes the file that declares `helper_value()`,
/// as `include` writes it.
fn project(name: &str, include: &str) -> TempDir {
    let dir = TempDir::new(name);
    dir.write("composer.json", "{}");
    dir.write(
        "vendor/composer/autoload_real.php",
        "<?php\n// autoload_real.php @generated by Composer\n",
    );
    dir.write(
        "vendor/composer/autoload_classmap.php",
        "<?php\n$vendorDir = dirname(__DIR__);\nreturn array(\n    'Acme\\\\Loader' => $vendorDir . '/acme/Loader.php',\n);\n",
    );
    dir.write(
        "vendor/composer/autoload_psr4.php",
        "<?php\n$vendorDir = dirname(__DIR__);\nreturn array(\n    'Acme\\\\' => array($vendorDir . '/acme'),\n);\n",
    );
    dir.write("vendor/acme/Loader.php", &format!("{LOADER}{include}"));
    dir.write("vendor/acme/helpers/functions.php", HELPERS);
    dir.write("src/Main.php", MAIN);
    dir
}

/// The output of `check-project` on `dir`, with the lazy context load on or
/// off.
fn check(dir: &TempDir, lazy: bool) -> String {
    let mut command = bin();
    command
        .current_dir(dir.path())
        .arg("check-project")
        .arg(dir.path().join("src"))
        .env("PHPSTAN_RS_NO_FILE_CACHE", "1");
    if lazy {
        command.env("PHPSTAN_RS_LAZY_CONTEXT", "1");
    } else {
        command.env_remove("PHPSTAN_RS_LAZY_CONTEXT");
    }
    let output = command.output().unwrap();
    assert!(output.status.success(), "{output:?}");
    String::from_utf8_lossy(&output.stdout).into_owned()
}

/// Asserts that the lazy load reports what the eager load reports, and that
/// `helper_value()` is known in both.
fn assert_same_as_eager(dir: &TempDir) {
    let eager = check(dir, false);
    let lazy = check(dir, true);
    assert_eq!(lazy, eager);
    assert!(!eager.contains("helper_value"), "got: {eager}");
}

#[test]
fn a_function_in_a_file_a_literal_include_names_is_known() {
    let dir = project(
        "lazy_literal_include",
        "\nrequire_once __DIR__ . '/helpers/functions.php';\n",
    );
    assert_same_as_eager(&dir);
}

#[test]
fn a_function_in_a_file_an_include_names_through_a_constant_is_known() {
    let dir = project(
        "lazy_constant_include",
        "\ndefine('ACME_ROOT', __DIR__ . '/');\nrequire_once ACME_ROOT . 'helpers/functions.php';\n",
    );
    assert_same_as_eager(&dir);
}

#[test]
fn a_function_in_a_file_a_path_not_known_may_name_is_known() {
    let dir = project(
        "lazy_dynamic_include",
        "\n$file = 'functions.php';\nrequire_once __DIR__ . '/helpers/' . $file;\n",
    );
    assert_same_as_eager(&dir);
}
