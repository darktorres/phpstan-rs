#[test]
fn a_real_mysql_version_hint_comment_with_an_unsupported_clause_does_not_abort_the_whole_table() {
    // The exact real shape from `install/piwigo_structure-mysql.sql`'s
    // own `categories` table - `sqlparser` 0.63.0 has no support for
    // `FULLTEXT`'s own `WITH PARSER` suffix at all, and its tokenizer
    // deliberately unwraps `/*!50100 ... */` into real tokens rather
    // than treating it as inert, so this fails to parse unless stripped
    // first.
    let catalog = parse_ddl(
        "CREATE TABLE categories (
            id int(10) unsigned NOT NULL,
            name varchar(255) NOT NULL,
            comment text,
            FULLTEXT KEY `categories_ft_name_comment` (`name`,`comment`) /*!50100 WITH PARSER `ngram` */
        ) ENGINE=InnoDB;",
        SqlDriver::Mysql,
    );
    let columns = catalog.table("categories").expect("table present");
    assert_eq!(columns.len(), 3);
}

#[test]
fn a_postgres_statement_this_project_does_not_need_failing_does_not_lose_its_create_table() {
    // The exact real shape from `install/piwigo_structure-pgsql.sql`:
    // an inline-sequence `ADD GENERATED ... AS IDENTITY (SEQUENCE NAME
    // ...)` clause `sqlparser` 0.63.0 can't parse, in a *separate*
    // `ALTER TABLE` statement after the real `CREATE TABLE`.
    let catalog = parse_ddl(
        "CREATE TABLE activity (activity_id bigint NOT NULL, system_scope smallint);
        ALTER TABLE public.activity ALTER COLUMN activity_id ADD GENERATED BY DEFAULT AS IDENTITY (
            SEQUENCE NAME public.activity_activity_id_seq
            START WITH 1
            INCREMENT BY 1
            NO MINVALUE
            NO MAXVALUE
        );",
        SqlDriver::Pgsql,
    );
    let columns = catalog.table("activity").expect("table present");
    assert_eq!(columns.len(), 2);
    assert_eq!(columns[0].name, "activity_id");
    assert_eq!(columns[0].ty, Type::Int);
}

#[test]
fn a_sqlite_virtual_table_this_project_does_not_need_failing_does_not_lose_the_real_table() {
    // The exact real shape from `install/piwigo_structure-sqlite.sql`:
    // an FTS5 virtual table `sqlparser` 0.63.0 can't parse as a real
    // table definition (its module-argument syntax isn't ordinary
    // column defs), declared right after the real `categories` table.
    let catalog = parse_ddl(
        "CREATE TABLE categories (id integer NOT NULL, name text NOT NULL);
        CREATE VIRTUAL TABLE categories_fts USING fts5(name, comment, content='categories', content_rowid='id', tokenize='trigram');",
        SqlDriver::Sqlite,
    );
    let columns = catalog.table("categories").expect("table present");
    assert_eq!(columns.len(), 2);
    assert!(catalog.table("categories_fts").is_none());
}

#[test]
fn parses_all_four_real_engines_worth_of_ddl_shape_from_one_generic_file() {
    // Not a substitute for running against the real corpus dump (no
    // committed test reads outside this repo - see this project's own
    // no-external-corpus-path-in-tests precedent) - just confirms the
    // parser/splitter combination handles a file mixing several
    // statement kinds together without losing any real `CREATE TABLE`.
    let sql = "
        CREATE TABLE a (id int NOT NULL, PRIMARY KEY (id));
        CREATE INDEX a_idx ON a (id);
        CREATE TABLE b (a_id int, FOREIGN KEY (a_id) REFERENCES a (id));
        COMMENT ON COLUMN a.id IS 'primary key';
    ";
    let catalog = parse_ddl(sql, SqlDriver::Pgsql);
    assert!(catalog.table("a").is_some());
    assert!(catalog.table("b").is_some());
}
